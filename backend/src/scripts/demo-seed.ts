// ============================================================================
// Demo seed (docs/demo-seed-plan.md): wipe app data and create 3 judge
// accounts, 7 traders with branded listings, taste profiles, past trades
// and a waiting offer for each judge. Then queue the real jobs (valuation,
// item taste, matches, taste compatibility) for the server's worker.
//
//   npx tsx src/scripts/demo-seed.ts                      dry run (no changes)
//   npx tsx src/scripts/demo-seed.ts --run --target=local
//   SEED_HOSTED_DATABASE_URL=... npx tsx src/scripts/demo-seed.ts \
//        --run --target=hosted --confirm-wipe-hosted
//   ... --judges-only        rebuild only the 3 judge accounts (no wipe)
//   ... --refresh-matches    re-queue every listing's matches (after tastes)
//   ... --retry-valuations   re-queue failed or stuck valuations
//   ... --check              report what judges will see
//
// Photos are 800 px (fewer input tokens per valuation: Groq's per-minute
// token limit throttled 1,200 px photos on the Oct 26 local run).
//
// Keeps categories, qloo_cache, qloo_usage and migrations. Logs counts and
// item ids only. Passwords live in docs/demo-credentials.md (not committed).
// ============================================================================
import 'dotenv/config';
import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import bcrypt from 'bcryptjs';
import {
   HISTORY,
   INTEREST_TYPES,
   JUDGE,
   JUDGE_OFFER,
   JUDGE_OFFER_TARGET,
   TRADERS,
   type HistoryItem,
   type Listing,
   type Slug,
} from './demo-seed/data';

type Db = (typeof import('../config/db.config'))['db'];

const HERE = dirname(fileURLToPath(import.meta.url));
const IMAGES = join(HERE, 'demo-seed', 'images');
const CREDENTIALS = join(HERE, '..', '..', '..', 'docs', 'demo-credentials.md');
const JUDGE_COUNT = 3;
const judgeEmail = (n: number) => `judge${n}@example.com`;
const traderEmail = (key: string) => `${key}@example.com`;
/** The judges' waiting offer must not expire before judging ends (rounds
 *  expire 3 h after round_started_at; the app never shows the timer). */
const OFFER_ROUND_START = new Date('2026-11-20T00:00:00Z');

const args = new Set(process.argv.slice(2));
const flag = (name: string) => args.has(`--${name}`);
const opt = (name: string) =>
   [...args].find((a) => a.startsWith(`--${name}=`))?.split('=')[1];

const RUN = flag('run');
const TARGET = opt('target') ?? 'local';
const JUDGES_ONLY = flag('judges-only');
const CHECK = flag('check');
const REFRESH = flag('refresh-matches');
const RETRY = flag('retry-valuations');

// ── Database target (set before the app modules load) ────────────────────────

function hostOf(url: string): string {
   try {
      return new URL(url).hostname;
   } catch {
      return '';
   }
}

if (TARGET === 'hosted') {
   const url = process.env.SEED_HOSTED_DATABASE_URL;
   if (!url || !hostOf(url).includes('supabase')) {
      console.error('hosted: set SEED_HOSTED_DATABASE_URL to the Supabase session pooler URL');
      process.exit(1);
   }
   if (RUN && !JUDGES_ONLY && !flag('confirm-wipe-hosted')) {
      console.error('hosted: this wipes Supabase; add --confirm-wipe-hosted');
      process.exit(1);
   }
   process.env.DATABASE_URL = url;
} else if (TARGET === 'local') {
   const host = hostOf(process.env.DATABASE_URL ?? '');
   if (!['127.0.0.1', 'localhost', '::1'].includes(host)) {
      console.error(`local: DATABASE_URL points at ${host || 'nothing'}, not a local database`);
      process.exit(1);
   }
} else {
   console.error('--target must be local or hosted');
   process.exit(1);
}
// Interest search and item taste need the Qloo feature on in this process.
process.env.QLOO_ENABLED = 'true';

// ── Helpers ─────────────────────────────────────────────────────────────────

const daysAgo = (n: number) => new Date(Date.now() - n * 86_400_000);
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

function credentials(): { judge: string; trader: string } {
   if (existsSync(CREDENTIALS)) {
      const text = readFileSync(CREDENTIALS, 'utf8');
      const judge = /Judge password: `([^`]+)`/.exec(text)?.[1];
      const trader = /Trader password: `([^`]+)`/.exec(text)?.[1];
      if (judge && trader) return { judge, trader };
   }
   const judge = `Swap-${randomBytes(5).toString('hex')}`;
   const trader = `Trader-${randomBytes(8).toString('hex')}`;
   mkdirSync(dirname(CREDENTIALS), { recursive: true });
   writeFileSync(
      CREDENTIALS,
      [
         '# Demo logins (generated by demo-seed.ts; not committed)',
         '',
         `Judge accounts: ${Array.from({ length: JUDGE_COUNT }, (_, i) => `\`${judgeEmail(i + 1)}\``).join(', ')}`,
         `Judge password: \`${judge}\``,
         '',
         `Traders (for testing only, never published): ${TRADERS.map((t) => `\`${traderEmail(t.key)}\``).join(', ')}`,
         `Trader password: \`${trader}\``,
         '',
      ].join('\n'),
   );
   return { judge, trader };
}

function ensurePhoto(file: string, unsplash?: string): Buffer {
   const path = join(IMAGES, file);
   if (!existsSync(path)) {
      throw new Error(
         `missing photo ${file}${unsplash ? ` (https://unsplash.com/photos/${unsplash}/download?force=true&w=800)` : ''}`,
      );
   }
   return readFileSync(path);
}

// ── Main ────────────────────────────────────────────────────────────────────

async function main() {
   const { db } = await import('../config/db.config');
   const { boss } = await import('../config/queue.config');

   const traderListings = TRADERS.reduce((n, t) => n + t.listings.length, 0);
   const interests = new Set([...JUDGE.interests, ...TRADERS.flatMap((t) => t.interests)]);
   console.log(
      `demo-seed: target=${TARGET} mode=${RUN ? 'run' : CHECK ? 'check' : REFRESH ? 'refresh-matches' : RETRY ? 'retry-valuations' : 'dry-run'}${JUDGES_ONLY ? ' judges-only' : ''}`,
   );

   if (CHECK) return check(db);
   if (REFRESH) return refreshMatches(db);
   if (RETRY) return retryValuations(db);

   console.log(
      `plan: ${JUDGES_ONLY ? 'rebuild' : 'wipe app data, then create'} ${JUDGE_COUNT} judges × ${JUDGE.listings.length} listings` +
         (JUDGES_ONLY ? '' : `, ${TRADERS.length} traders with ${traderListings} listings, ${HISTORY.length} past trades`) +
         `, ${JUDGE_COUNT} waiting offers; ${interests.size} interests to look up on Qloo (cached ones are free)`,
   );
   if (!RUN) {
      console.log('dry run: nothing changed. Add --run to apply.');
      return;
   }

   const pw = credentials();
   const [judgeHash, traderHash] = await Promise.all([bcrypt.hash(pw.judge, 10), bcrypt.hash(pw.trader, 10)]);
   const categories = new Map(
      (await db.category.findMany({ select: { id: true, slug: true } })).map((c) => [c.slug as Slug, c.id]),
   );
   if (categories.size < 9) throw new Error('expected the 9 categories; run npm run seed first');
   const cat = (s: Slug) => categories.get(s)!;

   // 1. Wipe ------------------------------------------------------------------
   if (JUDGES_ONLY) {
      await wipeJudges(db);
   } else {
      await db.$executeRawUnsafe(`
         TRUNCATE TABLE
            match_results, taste_compatibilities, user_taste_entities,
            item_wants, item_tastes, item_valuations, item_images,
            notifications, ratings, disputes, comments, messages,
            transactions, trade_offers, trade_items, trades, items,
            refresh_tokens, password_reset_tokens, otp_codes,
            rate_limit_attempts, users
         RESTART IDENTITY CASCADE`);
      await db.$executeRawUnsafe(`DELETE FROM pgboss.job`).catch(() => {});
      console.log('wiped app data (kept categories, qloo_cache, qloo_usage)');
   }

   // 2. Photos → R2 (once per file) ----------------------------------------------
   const { uploadToR2 } = await import('../services/r2.service');
   const runId = Date.now().toString(36);
   const urls = new Map<string, string>();
   const photoUrl = async (file: string, unsplash?: string) => {
      if (!urls.has(file)) {
         urls.set(file, await uploadToR2(`demo/${runId}/${file}`, ensurePhoto(file, unsplash), 'image/jpeg'));
      }
      return urls.get(file)!;
   };

   // 3. Users, listings, wants -------------------------------------------------
   const users = new Map<string, string>(); // key -> id
   const listingIds: string[] = []; // available listings (valuation, taste, matches)
   const now = new Date();

   const createUser = async (key: string, u: { firstName: string; lastName: string; email: string; location: string; bio: string; hash: string }) => {
      const row = await db.user.create({
         data: {
            firstName: u.firstName,
            lastName: u.lastName,
            email: u.email,
            password: u.hash,
            location: u.location,
            bio: u.bio,
            emailVerifiedAt: now,
            createdAt: daysAgo(30 + Math.floor(Math.random() * 20)),
         },
         select: { id: true },
      });
      users.set(key, row.id);
      return row.id;
   };

   const createListing = async (
      userId: string,
      location: string,
      l: Pick<Listing, 'title' | 'description' | 'category' | 'condition' | 'value' | 'photo' | 'unsplash' | 'isService'> & { wants?: Slug[] },
      status: 'available' | 'in_trade' | 'traded',
      createdAt: Date,
   ) => {
      const item = await db.item.create({
         data: {
            userId,
            categoryId: cat(l.category),
            title: l.title,
            description: l.description,
            condition: l.condition,
            status,
            isService: l.isService ?? false,
            location,
            userDeclaredValue: l.value,
            createdAt,
         },
         select: { id: true },
      });
      await db.itemImage.create({
         data: { itemId: item.id, url: await photoUrl(l.photo, l.unsplash), isPrimary: true, displayOrder: 0 },
      });
      if (l.wants) {
         await db.itemWant.createMany({
            data: l.wants.map((s, i) => ({ itemId: item.id, categoryId: cat(s), rank: i + 1, wasSuggested: true })),
         });
      }
      return item.id;
   };

   const historyItem = (userId: string, location: string, h: HistoryItem, status: 'in_trade' | 'traded', when: Date) =>
      createListing(
         userId,
         location,
         { title: h.title, description: `${h.title}.`, category: h.category, condition: 'good', value: h.value, photo: h.photo, unsplash: '' },
         status,
         when,
      );

   if (!JUDGES_ONLY) {
      for (const t of TRADERS) {
         const id = await createUser(t.key, {
            firstName: t.firstName,
            lastName: t.lastName,
            email: traderEmail(t.key),
            location: t.location,
            bio: t.bio,
            hash: traderHash,
         });
         for (const [i, l] of t.listings.entries()) {
            listingIds.push(await createListing(id, t.location, l, 'available', daysAgo(12 - i * 2 + Math.random())));
         }
      }
      console.log(`created ${TRADERS.length} traders, ${listingIds.length} listings`);
   } else {
      for (const t of TRADERS) {
         const u = await db.user.findUnique({ where: { email: traderEmail(t.key) }, select: { id: true } });
         if (!u) throw new Error('judges-only needs the traders from a full seed');
         users.set(t.key, u.id);
      }
   }

   const judgeListingIds: string[] = [];
   const judgeTargets: string[] = [];
   for (let n = 1; n <= JUDGE_COUNT; n++) {
      const id = await createUser(`judge${n}`, {
         firstName: JUDGE.firstName,
         lastName: `Judge ${n}`,
         email: judgeEmail(n),
         location: JUDGE.location,
         bio: JUDGE.bio,
         hash: judgeHash,
      });
      for (const [i, l] of JUDGE.listings.entries()) {
         const itemId = await createListing(id, JUDGE.location, l, 'available', daysAgo(3 - i * 0.5));
         judgeListingIds.push(itemId);
         if (l.key === JUDGE_OFFER_TARGET) judgeTargets.push(itemId);
      }
   }
   listingIds.push(...judgeListingIds);
   console.log(`created ${JUDGE_COUNT} judges, ${judgeListingIds.length} listings`);

   // 4. Taste profiles (Qloo search) ------------------------------------------
   const { defaultTasteQloo, searchTaste, replaceProfile } = await import('../services/tasteProfile.service');
   const qloo = await defaultTasteQloo();
   const found = new Map<string, Awaited<ReturnType<typeof searchTaste>>>();
   const lookUp = async (userId: string, name: string) => {
      if (!found.has(name)) {
         found.set(name, await searchTaste(qloo, userId, { q: name, type: INTEREST_TYPES[name] ?? 'brand', limit: 10 }));
      }
      const r = found.get(name)!;
      if (!r.ok || r.entities.length === 0) return null;
      const exact = r.entities.find((e) => e.name.toLowerCase() === name.toLowerCase());
      const e = exact ?? r.entities[0]!;
      return { qloo_entity_id: e.qloo_entity_id, name: e.name, entity_type: e.entity_type, image_url: e.image_url, tags: e.tags };
   };
   const profiles: [string, string[]][] = [
      ...(JUDGES_ONLY ? [] : TRADERS.map((t) => [t.key, t.interests] as [string, string[]])),
      ...Array.from({ length: JUDGE_COUNT }, (_, i) => [`judge${i + 1}`, JUDGE.interests] as [string, string[]]),
   ];
   let missing = 0;
   for (const [key, names] of profiles) {
      const userId = users.get(key)!;
      const entities = [];
      for (const name of names) {
         const e = await lookUp(userId, name);
         if (e) entities.push(e);
         else missing++;
      }
      // Unique ids only (two names can resolve to one entity).
      const unique = [...new Map(entities.map((e) => [e.qloo_entity_id, e])).values()];
      await replaceProfile(userId, unique as never);
   }
   console.log(`taste profiles: ${profiles.length} saved, ${missing} interest(s) not found on Qloo`);

   // 5. History and the judges' waiting offers ---------------------------------
   if (!JUDGES_ONLY) {
      const scores = new Map<string, number[]>();
      for (const h of HISTORY) {
         const proposer = users.get(h.proposer)!;
         const receiver = users.get(h.receiver)!;
         const when = daysAgo(h.daysAgo);
         const status = h.status === 'completed' ? 'traded' : 'in_trade';
         const pLoc = TRADERS.find((t) => t.key === h.proposer)!.location;
         const rLoc = TRADERS.find((t) => t.key === h.receiver)!.location;
         const pItem = await historyItem(proposer, pLoc, h.proposerItem, status, daysAgo(h.daysAgo + 7));
         const rItem = await historyItem(receiver, rLoc, h.receiverItem, status, daysAgo(h.daysAgo + 9));
         const trade = await db.trade.create({
            data: {
               proposerId: proposer,
               receiverId: receiver,
               tradeType: 'item',
               status: h.status,
               currentOfferBy: proposer,
               awaitingResponseFrom: null,
               roundStartedAt: when,
               completionMethod: 'meetup',
               meetupDetails: 'Agreed in chat',
               proposerConfirmed: h.status === 'completed',
               receiverConfirmed: h.status === 'completed',
               completedAt: h.status === 'completed' ? when : null,
               createdAt: daysAgo(h.daysAgo + 2),
            },
            select: { id: true },
         });
         await db.tradeItem.createMany({
            data: [
               { tradeId: trade.id, itemId: rItem, offeredBy: receiver, side: 'receiver' },
               { tradeId: trade.id, itemId: pItem, offeredBy: proposer, side: 'proposer' },
            ],
         });
         await db.tradeOffer.create({
            data: { tradeId: trade.id, offeredBy: proposer, tradeType: 'item', topUpAmount: h.topUp ?? null, offeredItemIds: [pItem], isCurrent: true, createdAt: daysAgo(h.daysAgo + 2) },
         });
         await db.transaction.create({
            data: {
               tradeId: trade.id,
               tradeType: 'item',
               proposerId: proposer,
               receiverId: receiver,
               receiverItemId: rItem,
               offeredItemIds: [pItem],
               agreedTopUpAmount: h.topUp ?? null,
               status: h.status === 'completed' ? 'completed' : 'pending_completion',
               agreedAt: daysAgo(h.daysAgo + 1),
               completedAt: h.status === 'completed' ? when : null,
            },
         });
         for (const [i, [sender, body]] of (h.messages ?? []).entries()) {
            await db.message.create({
               data: { tradeId: trade.id, senderId: users.get(sender)!, body, readAt: when, createdAt: new Date(when.getTime() + i * 600_000) },
            });
         }
         if (h.status === 'completed' && h.ratings) {
            const [toReceiver, toProposer] = h.ratings;
            await db.rating.createMany({
               data: [
                  { tradeId: trade.id, raterId: proposer, ratedId: receiver, score: toReceiver, review: h.reviews?.[0] ?? null, createdAt: when },
                  { tradeId: trade.id, raterId: receiver, ratedId: proposer, score: toProposer, review: h.reviews?.[1] ?? null, createdAt: when },
               ],
            });
            scores.set(receiver, [...(scores.get(receiver) ?? []), toReceiver]);
            scores.set(proposer, [...(scores.get(proposer) ?? []), toProposer]);
            await db.user.updateMany({ where: { id: { in: [proposer, receiver] } }, data: { totalTrades: { increment: 1 } } });
         }
      }
      for (const [userId, list] of scores) {
         const avg = list.reduce((a, b) => a + b, 0) / list.length;
         await db.user.update({ where: { id: userId }, data: { averageRating: Number(avg.toFixed(2)) } });
      }
      console.log(`history: ${HISTORY.length} trades, ratings for ${scores.size} traders`);
   }

   const offerFrom = users.get(JUDGE_OFFER.from)!;
   const offerLoc = TRADERS.find((t) => t.key === JUDGE_OFFER.from)!.location;
   for (const [n, target] of judgeTargets.entries()) {
      const judgeId = users.get(`judge${n + 1}`)!;
      const offered = await createListing(
         offerFrom,
         offerLoc,
         { title: JUDGE_OFFER.item.title, description: 'Samsung Galaxy Buds2, graphite, with charging case. Like new.', category: JUDGE_OFFER.item.category, condition: 'good', value: JUDGE_OFFER.item.value, photo: JUDGE_OFFER.item.photo, unsplash: '' },
         'in_trade',
         daysAgo(4),
      );
      listingIds.push(offered); // valued, so the fairness meter has both sides
      await db.item.update({ where: { id: target }, data: { status: 'in_trade' } });
      const trade = await db.trade.create({
         data: {
            proposerId: offerFrom,
            receiverId: judgeId,
            tradeType: 'item',
            status: 'negotiating',
            currentOfferBy: offerFrom,
            awaitingResponseFrom: judgeId,
            roundStartedAt: OFFER_ROUND_START,
            createdAt: daysAgo(0.2),
         },
         select: { id: true },
      });
      await db.tradeItem.createMany({
         data: [
            { tradeId: trade.id, itemId: target, offeredBy: judgeId, side: 'receiver' },
            { tradeId: trade.id, itemId: offered, offeredBy: offerFrom, side: 'proposer' },
         ],
      });
      await db.tradeOffer.create({
         data: { tradeId: trade.id, offeredBy: offerFrom, tradeType: 'item', topUpAmount: JUDGE_OFFER.topUp, offeredItemIds: [offered], isCurrent: true },
      });
      await db.message.create({ data: { tradeId: trade.id, senderId: offerFrom, body: JUDGE_OFFER.message } });
      await db.notification.create({
         data: { userId: judgeId, type: 'trade_request', title: 'New trade proposal', body: 'Someone has proposed a trade for one of your items.', referenceId: trade.id, referenceType: 'Trade' },
      });
   }
   console.log(`waiting offers: ${judgeTargets.length}`);

   // 6. Jobs for the worker -----------------------------------------------------
   const { enqueueItemValuation } = await import('../queue/itemValuation.queue');
   const { requestItemTaste } = await import('../services/itemTaste.service');
   const { queueMatchRefresh } = await import('../services/matchRefresh.service');
   const { queueTasteCompat } = await import('../services/tasteCompat.service');
   for (const itemId of listingIds) {
      const v = await db.itemValuation.create({ data: { itemId, status: 'pending', currency: 'USD' }, select: { id: true } });
      await enqueueItemValuation({ itemId, valuationId: v.id });
      await requestItemTaste(itemId, { reset: true });
      await queueMatchRefresh(itemId, 'publish');
      await sleep(334); // same pacing as the backfill
   }
   for (const key of users.keys()) await queueTasteCompat(users.get(key)!, 'profile');
   console.log(
      `queued: ${listingIds.length} valuations + item tastes + match refreshes, ${users.size} taste-compat jobs. ` +
         `The ${TARGET === 'hosted' ? 'Render' : 'local'} worker processes them (~10 min). Then run --refresh-matches, then --check.`,
   );
   console.log(`logins: ${CREDENTIALS.replace(/.*\/docs\//, 'docs/')}`);
   await boss.stop({ graceful: true }).catch(() => {});
}

/** Delete the judge accounts and everything theirs (for --judges-only). */
async function wipeJudges(db: Db) {
   const judges = (
      await db.user.findMany({
         where: { email: { in: Array.from({ length: JUDGE_COUNT }, (_, i) => judgeEmail(i + 1)) } },
         select: { id: true },
      })
   ).map((u: { id: string }) => u.id);
   if (judges.length === 0) return;
   const trades = (
      await db.trade.findMany({ where: { OR: [{ proposerId: { in: judges } }, { receiverId: { in: judges } }] }, select: { id: true } })
   ).map((t: { id: string }) => t.id);
   const tradeItems = (await db.tradeItem.findMany({ where: { tradeId: { in: trades } }, select: { itemId: true } })).map(
      (t: { itemId: string }) => t.itemId,
   );
   const judgeItems = (await db.item.findMany({ where: { userId: { in: judges } }, select: { id: true } })).map((i: { id: string }) => i.id);
   // The traders' items offered to judges (only ever used in those offers).
   const offeredOnly = tradeItems.filter((id: string) => !judgeItems.includes(id));
   const items = [...judgeItems, ...offeredOnly];
   await db.$transaction([
      db.notification.deleteMany({ where: { userId: { in: judges } } }),
      db.message.deleteMany({ where: { tradeId: { in: trades } } }),
      db.rating.deleteMany({ where: { tradeId: { in: trades } } }),
      db.transaction.deleteMany({ where: { tradeId: { in: trades } } }),
      db.tradeOffer.deleteMany({ where: { tradeId: { in: trades } } }),
      db.tradeItem.deleteMany({ where: { tradeId: { in: trades } } }),
      db.trade.deleteMany({ where: { id: { in: trades } } }),
      db.matchResult.deleteMany({ where: { OR: [{ sourceItemId: { in: items } }, { candidateItemId: { in: items } }] } }),
      db.itemWant.deleteMany({ where: { itemId: { in: items } } }),
      db.itemTaste.deleteMany({ where: { itemId: { in: items } } }),
      db.itemValuation.deleteMany({ where: { itemId: { in: items } } }),
      db.itemImage.deleteMany({ where: { itemId: { in: items } } }),
      db.comment.deleteMany({ where: { OR: [{ itemId: { in: items } }, { userId: { in: judges } }] } }),
      db.item.deleteMany({ where: { id: { in: items } } }),
      db.tasteCompatibility.deleteMany({ where: { OR: [{ userAId: { in: judges } }, { userBId: { in: judges } }] } }),
      db.userTasteEntity.deleteMany({ where: { userId: { in: judges } } }),
      db.refreshToken.deleteMany({ where: { userId: { in: judges } } }),
      db.user.deleteMany({ where: { id: { in: judges } } }),
   ]);
   console.log(`removed ${judges.length} judge accounts, ${items.length} items, ${trades.length} trades`);
}

/** Re-queue matches for every available listing with wants (after tastes),
 *  and taste compatibility for everyone with a profile. */
async function refreshMatches(db: Db) {
   const { queueMatchRefresh } = await import('../services/matchRefresh.service');
   const { boss } = await import('../config/queue.config');
   const items = await db.item.findMany({ where: { status: 'available', deletedAt: null, wants: { some: {} } }, select: { id: true } });
   for (const i of items) await queueMatchRefresh(i.id, 'wants_change');
   // And everyone's taste compatibility (pairs follow the current rules).
   const { queueTasteCompat } = await import('../services/tasteCompat.service');
   const people = await db.userTasteEntity.findMany({ distinct: ['userId'], select: { userId: true } });
   for (const p of people) await queueTasteCompat(p.userId, 'profile');
   console.log(`re-queued matches for ${items.length} listings and compatibility for ${people.length} people`);
   await boss.stop({ graceful: true }).catch(() => {});
}

/** Re-queue valuations that failed, or have been pending over 10 min. */
async function retryValuations(db: Db) {
   const { enqueueItemValuation } = await import('../queue/itemValuation.queue');
   const { boss } = await import('../config/queue.config');
   const rows = await db.itemValuation.findMany({
      where: {
         OR: [{ status: 'failed' }, { status: 'pending', updatedAt: { lt: new Date(Date.now() - 600_000) } }],
         item: { deletedAt: null },
      },
      select: { id: true, itemId: true },
   });
   for (const r of rows) {
      await db.itemValuation.update({ where: { id: r.id }, data: { status: 'pending', failedReason: null } });
      await enqueueItemValuation({ itemId: r.itemId, valuationId: r.id });
      await sleep(2000); // gentle on Groq's per-minute limits
   }
   console.log(`re-queued ${rows.length} valuations`);
   await boss.stop({ graceful: true }).catch(() => {});
}

/** What a judge will see. Pass: every listing ≥ 3 matches incl. strong/good,
 *  People like you ≥ 4, all valuations completed. */
async function check(db: Db) {
   const judges = await db.user.findMany({
      where: { email: { in: Array.from({ length: JUDGE_COUNT }, (_, i) => judgeEmail(i + 1)) } },
      select: { id: true, email: true },
      orderBy: { email: 'asc' },
   });
   const [vals, tastes] = await Promise.all([
      db.itemValuation.groupBy({ by: ['status'], _count: { _all: true } }),
      db.itemTaste.groupBy({ by: ['status'], _count: { _all: true } }),
   ]);
   const fmt = (rows: { status: string; _count: { _all: number } }[]) => rows.map((r) => `${r.status} ${r._count._all}`).join(', ');
   console.log(`valuations: ${fmt(vals)}`);
   console.log(`item tastes: ${fmt(tastes)}`);
   let pass = !vals.some((v: { status: string }) => v.status !== 'completed');
   for (const j of judges) {
      const items = await db.item.findMany({ where: { userId: j.id, status: 'available' }, select: { id: true, title: true } });
      const lines: string[] = [];
      for (const it of items) {
         const rows = await db.matchResult.findMany({ where: { sourceItemId: it.id }, select: { explanation: true } });
         const labels = rows.map((r) => (r.explanation as { score_label?: string } | null)?.score_label ?? 'none');
         const strongGood = labels.filter((l: string) => l === 'strong' || l === 'good').length;
         if (rows.length < 3 || strongGood === 0) pass = false;
         lines.push(`${it.title}: ${rows.length} matches (${strongGood} strong/good)`);
      }
      const people = await db.tasteCompatibility.count({
         where: {
            score: { gte: 0.1 },
            OR: [
               { userAId: j.id, userB: { items: { some: { status: 'available', deletedAt: null } } } },
               { userBId: j.id, userA: { items: { some: { status: 'available', deletedAt: null } } } },
            ],
         },
      });
      if (people < 4) pass = false;
      console.log(`${j.email.split('@')[0]}: people like you ${people}; ${lines.join('; ')}`);
   }
   console.log(pass ? 'CHECK PASS' : 'CHECK NOT YET (jobs may still be running; wait and re-run)');
}

